test("CUI Section motion reuses groups and settles the latest requested direction", function()
    local _, addon, state, panel, C = Fixture()
    local before, settled, toggled = copy(addon.db), 0, 0
    local section = C.Section(panel, "Disclosure", 0, -100, 640, { height = 240, collapsible = true,
        onToggle = function() toggled = toggled + 1 end,
        onSettled = function() settled = settled + 1 end })
    local frames, groups = #state.frames, #state.animations
    equal(section.expandAnimation.animations[1].duration, .12)
    equal(section.collapseAnimation.animations[1].duration, .12)
    section:SetCollapsed(true)
    truthy(section.content:IsShown() and section.content.cuiSectionLocked)
    equal(section:GetHeight(), 240); equal(section.transition, "collapsing")
    local oldCollapse = section.collapseAnimation:GetScript("OnFinished")
    section.collapseButton:Click()
    equal(section.transition, "expanding"); truthy(not section.collapseAnimation:IsPlaying())
    Finish(section.collapseAnimation)
    equal(section.transition, "expanding", "an outgoing completion cannot settle the opposite direction")
    Finish(section.expandAnimation)
    equal(section.transition, nil); equal(section.content.cuiSectionLocked, false); equal(settled, 1)
    section:SetCollapsed(true); oldCollapse(section.collapseAnimation)
    equal(section.transition, "collapsing", "an earlier same-direction completion cannot finish a newer fade")
    section:SetCollapsed(false); Finish(section.expandAnimation)
    for _ = 1, 5 do section:SetCollapsed(true); section:SetCollapsed(false) end
    C.StopMotion(panel)
    equal(section.transition, nil); equal(section:GetHeight(), 240); truthy(section.content:IsShown())
    section:SetCollapsed(true); C.StopMotion(panel)
    equal(section:GetHeight(), 42); truthy(not section.content:IsShown())
    Finish(section.expandAnimation); Finish(section.collapseAnimation)
    equal(section:GetHeight(), 42); equal(section.transition, nil)
    section:SetCollapsed(false); section:Hide()
    equal(section:GetHeight(), 240); equal(section.transition, nil)
    truthy(section.content.cuiSectionLocked)
    section:Show(); equal(section.content.cuiSectionLocked, false)
    truthy(not section.expandAnimation:IsPlaying() and not section.collapseAnimation:IsPlaying())
    equal(#state.frames, frames); equal(#state.animations, groups)
    truthy(toggled > settled); same(addon.db, before)
end)

test("CUI Section guards new inputs stale popup callbacks and current logical enabled states", function()
    local env, _, _, panel, C = Fixture()
    local changes = 0
    local section = C.Section(panel, "Disclosure", 0, -100, 640, { height = 240, collapsible = true, collapsed = true })
    local button = C.Button(section.content, "Action", 0, 0, 100, function() changes = changes + 1 end)
    local edit = C.EditBox(panel, section.content, 120, 0, 100)
    edit:SetScript("OnEnterPressed", function() changes = changes + 1 end)
    local dropdown = C.Dropdown(panel, section.content, "Choice", 0, -50,
        { { value = 1, label = "One" } }, nil, function() changes = changes + 1 end)
    local staleOpen, staleEnter = dropdown:GetScript("OnClick"), edit:GetScript("OnEnterPressed")
    button:EnableMouse(true); edit:EnableMouse(true); dropdown:EnableMouse(true)
    truthy(not button:IsEnabled() and not edit:IsEnabled() and not dropdown:IsEnabled())
    edit:SetFocus(); staleEnter(edit); staleOpen(dropdown); button:GetScript("OnClick")(button)
    equal(changes, 0); truthy(not edit:HasFocus() and not dropdown.menu:IsShown())
    section:SetCollapsed(false)
    edit:SetScript("OnEnterPressed", function() changes = changes + 2 end)
    edit:GetScript("OnEnterPressed")(edit); equal(changes, 0, "later script replacement retains the input guard")
    button:Disable(); edit:Disable(); edit:SetEnabled(true)
    truthy(not edit:IsEnabled(), "logical enable requests cannot bypass a running fade")
    Finish(section.expandAnimation)
    truthy(not button:IsEnabled() and edit:IsEnabled() and dropdown:IsEnabled())
    truthy(edit:IsMouseEnabled()); edit:SetFocus(); truthy(edit:HasFocus())
    edit:GetScript("OnEnterPressed")(edit); equal(changes, 2)
    dropdown:Click(); truthy(dropdown.menu:IsShown())
    section:SetCollapsed(true)
    truthy(not edit:HasFocus() and not dropdown.menu:IsShown())
    truthy(not dropdown.menu.cuiInteractive and not dropdown.choices[1]:IsEnabled())
    staleOpen(dropdown); dropdown.choices[1]:GetScript("OnClick")(dropdown.choices[1])
    truthy(not dropdown.menu:IsShown()); equal(changes, 2)
    button:Enable(); edit:Disable(); section:SetCollapsed(false); Finish(section.expandAnimation)
    truthy(button:IsEnabled() and not edit:IsEnabled(), "rapid reversal restores the latest page-requested state")
    local raw = env.CreateFrame("Button", nil, section.content)
    raw:SetScript("OnClick", function() changes = changes + 4 end)
    section:SetCollapsed(true)
    raw:GetScript("OnClick")(raw); equal(changes, 2, "existing raw descendants are guarded before collapse")
end)

test("CUI Section blocks user changes while preserving programmatic refresh and scroll geometry", function()
    local env, _, _, panel, C = Fixture()
    local section = C.Section(panel, "Disclosure", 0, -100, 640, { height = 240, collapsible = true })
    local slider = C.Slider(panel, section.content, "Number", 0, { min = 0, max = 10 }, 1, function(value) return { value = value } end)
    local scroll = C.ScrollFrame(panel, section.content, 0, -90, 400, 100)
    local content = env.CreateFrame("Frame", nil, scroll); content:SetSize(400, 400)
    scroll:SetScrollChild(content); scroll:RefreshRange()
    slider.valueButton:Click(); section:SetCollapsed(true)
    truthy(not slider:IsEnabled() and not slider.editBox:IsEnabled() and not slider.editBox:HasFocus())
    slider.slider:GetScript("OnValueChanged")(slider.slider, 8, true)
    slider.editBox:GetScript("OnEnterPressed")(slider.editBox)
    scroll:GetScript("OnMouseWheel")(scroll, -2)
    equal(#panel.submissions, 0); equal(scroll:GetVerticalScroll(), 0)
    panel.refreshing = true; slider:SetValue(6); slider.editBox:SetText("6"); panel.refreshing = false
    truthy(slider.fill:GetWidth() > 0); equal(slider.editBox:GetText(), "6")
    equal(#panel.submissions, 0, "programmatic refresh retains the existing submission gate")
