    slider:Disable()
    section:SetCollapsed(false); Finish(section.expandAnimation)
    truthy(not slider:IsEnabled() and not slider.editBox:IsEnabled(), "a logical slider disable while locked also disables its numeric input")
    section:SetCollapsed(true); slider:Enable()
    truthy(not slider:IsEnabled() and not slider.editBox:IsEnabled())
    section:SetCollapsed(false); Finish(section.expandAnimation)
    truthy(slider:IsEnabled() and slider.editBox:IsEnabled(), "logical enable while locked restores both slider inputs")
    scroll:GetScript("OnMouseWheel")(scroll, -2); equal(scroll:GetVerticalScroll(), 60)
